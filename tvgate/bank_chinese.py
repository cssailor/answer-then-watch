def build():
    random.seed(20250402)
    out, seen = [], set()
    counter = [0]

    def add(kp, difficulty, stem, correct, distractors, explain=""):
        if stem in seen:
            return
        seen.add(stem)
        opts = [correct]
        for d in distractors:
            if d not in opts:
                opts.append(d)
        n = 1
        while len(opts) < 4:
            cand = correct + "（干扰%d）" % n
            if cand not in opts:
                opts.append(cand)
            n += 1
        opts = opts[:4]
        random.shuffle(opts)
        counter[0] += 1
        out.append({
            "id": "g4c-%03d" % counter[0],
            "subject": "语文", "grade": 4, "kp": kp,
            "difficulty": difficulty, "stem": stem,
            "options": opts, "answer": opts.index(correct),
            "explain": explain,
        })

    for word, target, right, wrongs in PINYIN:
        add("字音", 1, "“%s”中“%s”的正确读音是？" % (word, target), right, wrongs,
            "注意声调和声母。")
    for idx, (right, wrongs) in enumerate(SPELLING, 1):
        add("字形", 1, "下列词语书写完全正确的一项是？（第 %d 组）" % idx,
            right, wrongs, "注意形近字和同音字。")
    for idiom, right, wrongs in IDIOMS:
        add("成语", 2, "“%s”的意思是？" % idiom, right, wrongs,
            "结合成语故事理解。")
    for stem, right, wrongs, explain in SENTENCES:
        add("句子", 2, stem, right, wrongs, explain)
    for stem, right, wrongs, explain in POEMS:
        add("古诗文", 2, stem, right, wrongs, explain)
    for stem, right, wrongs, explain in LITERATURE:
        add("文学常识", 1, stem, right, wrongs, explain)
    for passage, questions in READING:
        for stem, right, wrongs in questions:
            full = "阅读短文，回答问题：\n\n%s\n\n%s" % (passage, stem)
            add("阅读理解", 3, full, right, wrongs, "回到短文中找依据。")

    return out
